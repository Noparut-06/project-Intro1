const facultySelect = document.querySelector("#faculty");
const programSelect = document.querySelector("#program");

facultySelect.addEventListener("change", () => {
    programSelect.replaceChildren(new Option("เลือกสาขาวิชา / หลักสูตร", ""));

    for (const groupData of programOptions[facultySelect.value] ?? []) {
        const group = document.createElement("optgroup");
        group.label = groupData.label;

        for (const [value, label] of groupData.programs) {
            group.append(new Option(label, value));
        }

        programSelect.append(group);
    }

    programSelect.disabled = programSelect.options.length === 1;
});
